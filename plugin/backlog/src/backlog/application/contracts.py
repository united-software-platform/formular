"""Контракты чтения модуля беклога.

Контракты объявлены в слое приложения, а не в домене: их реализации обязаны обратиться
к носителям — файлу шаблона и каталогу беклогов, — а домен объявляет только то, что выполнимо
в его собственных терминах.
"""

import abc


class TemplateSource(abc.ABC):
    """Шаблон операции: его версия и текст."""

    @abc.abstractmethod
    def read(self, operation):
        """Возвращает пару (версия шаблона, текст) шаблона названной операции."""


class BacklogLookup(abc.ABC):
    """Наличие порождённого беклога и его адрес.

    Контракт узкий намеренно: порождению нужны один факт и один адрес — порождён ли беклог
    этой операции над этим предметом и где он лежит. Содержимое беклога порождению не нужно,
    и чтение его состава в один контракт с этим фактом не смешивается.

    Адрес входит в контракт, потому что его называет отказ: владельцу, которому сказано
    «беклог уже порождён», нужно знать, какой файл исполнять, а путь знает носитель.
    """

    @abc.abstractmethod
    def exists(self, operation, subject):
        """Порождён ли беклог названной операции над названным предметом."""

    @abc.abstractmethod
    def path_of(self, operation, subject):
        """Адрес беклога названной операции над названным предметом."""


class DeliverySource(abc.ABC):
    """Состав поставки: файлы, которые ставятся в дерево проекта.

    Перечень называет сама поставка, а не сценарий: перечень, записанный в сценарии,
    разошёлся бы с её содержимым при первом же пополнении состава.
    """

    @abc.abstractmethod
    def items(self):
        """Возвращает состав поставки: путь в проекте, текст и слепок каждого файла."""


class ProjectTree(abc.ABC):
    """Дерево целевого проекта: слепки лежащих файлов, запись и строки подключения.

    Контракт объявлен в слое приложения: его реализация обязана обратиться к файловой
    системе, а домен объявляет только то, что выполнимо в его собственных терминах.
    """

    @abc.abstractmethod
    def digest_of(self, path):
        """Слепок лежащего файла либо None, если файла нет."""

    @abc.abstractmethod
    def write(self, path, text):
        """Пишет файл проекта, заводя каталоги по пути."""

    @abc.abstractmethod
    def has_line(self, path, text):
        """Есть ли в файле проекта названная строка."""

    @abc.abstractmethod
    def add_line(self, path, text, after):
        """Дописывает строку в файл проекта — после названной строки либо в конец."""


class ManifestStore(abc.ABC):
    """Манифест установленного: версия поставки, время установки и слепки файлов."""

    @abc.abstractmethod
    def read(self):
        """Возвращает установленное прежде: версию поставки и слепки файлов."""

    @abc.abstractmethod
    def write(self, version, installed_at, files):
        """Записывает манифест установленного."""
