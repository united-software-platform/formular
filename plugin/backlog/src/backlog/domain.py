"""Домен беклога: носитель порядка работ и следа исполнения одной операции.

Беклог адресуется парой «операция и предмет»: операция `sample-operation` над предметом
`20261008120000`. Предмет назван строкой, пригодной сегментом пути, потому что по этой паре
беклог и находится — второго способа его адресовать нет. Предмет повторяемой операции есть
штамп прогона, предмет операции, выполнимой однажды, — предмет предметной области.

Порождённый беклог по составу задач не правится: он называет версию шаблона, которой порождён,
и правка шаблона действует на следующие операции, а не задним числом на состоявшиеся. Поэтому
контракт записи заводит беклог, но не перезаписывает его: отказ — исход операции, а не ошибка.

О формате файла домен не знает: ни о фронтматтере, ни о Markdown, ни о грамматике подстановок.
Это забота адаптера — беклог для домена есть операция, предмет, версия шаблона и значения
исполнения.
"""

import abc
import dataclasses

# Исходы заведения беклога контрактом записи.
BACKLOG_WRITTEN = "written"
BACKLOG_EXISTS = "exists"


@dataclasses.dataclass(frozen=True)
class Backlog:
    """Беклог операции: имя операции, предмет, версия шаблона и значения исполнения.

    Неизменяем: ход исполнения правит файл отметками задач и дописанными во фронтматтер
    значениями, но порождённый состав задач остаётся тем, каким его дал шаблон.
    """

    operation: str
    subject: str
    template_version: str
    values: dict

    @property
    def address(self):
        """Пара, которой беклог адресуется: операция и предмет."""
        return self.operation, self.subject


class BacklogRepository(abc.ABC):
    """Контракт записи беклогов: заводит беклог целиком, принимая агрегат.

    Операции «правь задачу» у контракта нет намеренно. Отметки задач ставит исполнитель
    по ходу работ, и это исполнение беклога, а не его порождение: механизм порождения
    переписывать состоявшийся файл не вправе.
    """

    @abc.abstractmethod
    def add(self, backlog, text):
        """Заводит беклог. Возвращает BACKLOG_WRITTEN либо BACKLOG_EXISTS."""
